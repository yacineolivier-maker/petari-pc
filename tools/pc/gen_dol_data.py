#!/usr/bin/env python3
"""Generate C++ definitions for data objects the decomp still takes from the original binary.

A few data tables (embedded BCSV tables like cGalaxyInfoTable) are not decompiled: on the Wii
they are linked from the original assembly. For the PC build they are copied out of the user's
own main.dol at build time, into the build directory (never committed).

Usage: python tools/pc/gen_dol_data.py <main.dol> <symbols.txt> <out.cpp>
"""

import re
import struct
import sys
from pathlib import Path

# symbol name -> (header declaring it, C++ declaration of the definition)
OBJECTS = {
    "cGalaxyInfoTable": ("Game/System/GalaxyInfoTable.hpp", "extern const u8 cGalaxyInfoTable[]"),
    "cStoryProgressTable": ("Game/System/StoryProgressTable.hpp", "extern const u8 cStoryProgressTable[]"),
}


def read_dol(path):
    data = Path(path).read_bytes()
    offsets = struct.unpack(">18I", data[0x00:0x48])
    addrs = struct.unpack(">18I", data[0x48:0x90])
    sizes = struct.unpack(">18I", data[0x90:0xD8])
    sections = [(a, o, s) for o, a, s in zip(offsets, addrs, sizes) if s]
    return data, sections


def read_va(dol, sections, va, size):
    for addr, off, sz in sections:
        if addr <= va and va + size <= addr + sz:
            start = off + (va - addr)
            return dol[start:start + size]
    raise ValueError(f"address {va:#x} (+{size:#x}) is not in a DOL section")


def main():
    dol_path, symbols_path, out_path = sys.argv[1:4]
    dol, sections = read_dol(dol_path)
    symbols = {}
    for line in Path(symbols_path).read_text(encoding="utf-8").splitlines():
        m = re.match(r"(\S+) = \.\w+:0x([0-9A-Fa-f]+); // type:object size:0x([0-9A-Fa-f]+)", line)
        if m:
            symbols[m.group(1)] = (int(m.group(2), 16), int(m.group(3), 16))
    out = ["// Generated by tools/pc/gen_dol_data.py from the user's main.dol. Do not edit or commit.", ""]
    for header, _ in OBJECTS.values():
        out.append(f'#include "{header}"')
    out.append("")
    for name, (_, decl) in OBJECTS.items():
        va, size = symbols[name]
        blob = read_va(dol, sections, va, size)
        # Embedded tables are read through pointers to u32/f32 fields: keep them 32-byte aligned.
        out.append(f"alignas(32) {decl} = {{")
        for i in range(0, len(blob), 16):
            out.append("    " + ", ".join(f"0x{b:02X}" for b in blob[i:i + 16]) + ",")
        out.append("};")
        out.append("")
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    Path(out_path).write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {out_path} ({len(OBJECTS)} objects)")


if __name__ == "__main__":
    main()
