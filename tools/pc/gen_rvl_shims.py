#!/usr/bin/env python3
"""Generate pc/include/revolution/* shims that map the Wii SDK header layout onto Aurora.

Aurora implements the GameCube SDK (dolphin/*). The Wii SDK's GX, OS, VI, DVD, PAD, MTX and GD
APIs are the same, so each revolution/<path> header that has an Aurora equivalent becomes a
one-line include of dolphin/<path>. Wii SDK headers in those areas without an equivalent include
the closest Aurora umbrella header. Everything else (WPAD, KPAD, NAND, SC, ...) is left to the
original headers in libs/RVL_SDK/include, which the PC layer implements.

Hand-written shims (marked with "// PC shim (manual)") are never overwritten.

Usage: python tools/pc/gen_rvl_shims.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RVL = ROOT / "libs/RVL_SDK/include"
AUR = ROOT / "extern/aurora/include"
OUT = ROOT / "pc/include"

MAPPED_AREAS = ("gx", "os", "mtx", "vi", "dvd", "pad", "gd", "base", "si", "ai", "dsp", "exi", "card", "db", "thp")
UMBRELLA = {
    "gx": "dolphin/gx.h",
    "os": "dolphin/os.h",
    "vi": "dolphin/vi.h",
    "gd": "dolphin/gd.h",
    "base": "dolphin/base/PPCArch.h",
}


def area_of(rel: str) -> str:
    parts = rel.split("/")
    if len(parts) == 2:
        return parts[1][:-2]
    return parts[1]


def main():
    written = 0
    for hdr in sorted(RVL.glob("revolution/**/*.h")):
        rel = hdr.relative_to(RVL).as_posix()
        area = area_of(rel)
        if area not in MAPPED_AREAS:
            continue
        dol = "dolphin/" + rel[len("revolution/"):]
        if (AUR / dol).exists():
            target = dol
        elif area in UMBRELLA:
            target = UMBRELLA[area]
        else:
            continue
        out = OUT / rel
        if out.exists() and "PC shim (manual)" in out.read_text(encoding="utf-8"):
            continue
        out.parent.mkdir(parents=True, exist_ok=True)
        text = (
            "#pragma once\n"
            "// PC shim (generated by tools/pc/gen_rvl_shims.py): Wii SDK header -> Aurora.\n"
            f"#include <{target}>\n"
            f"#include <revolution/pc_extras/{area}.h>\n"
        )
        out.write_text(text, encoding="utf-8")
        written += 1
    print(f"wrote {written} shims")


if __name__ == "__main__":
    main()
