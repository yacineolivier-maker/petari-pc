#!/usr/bin/env python3
"""Generate files.cmake for the PC build from the library lists in configure.py.

configure.py stays the single source of truth for which source files exist. This runs it with
generate_build() swapped out and writes one CMake list per library:

    set(LIB_<name>_FILES src/... src/...)

Library names are sanitized for CMake (dots and dashes become underscores).

Usage: python tools/gen_pc_files.py
"""

import re
import runpy
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import tools.project as project  # noqa: E402

OUT = ROOT / "files.cmake"

captured = {}


def capture(config):
    captured["config"] = config


def main():
    project.generate_build = capture
    sys.argv = ["configure.py", "--version", "RMGE01"]
    runpy.run_path(str(ROOT / "configure.py"), run_name="__main__")
    config = captured["config"]

    lines = ["# Generated by tools/gen_pc_files.py from configure.py. Do not edit.", ""]
    names = []
    seen = set()
    for lib in config.libs:
        name = re.sub(r"[^A-Za-z0-9_]", "_", lib["lib"])
        files = []
        for obj in lib["objects"]:
            src = obj.options.get("source") or obj.name
            path = ROOT / "src" / src
            if path.suffix not in (".c", ".cpp"):
                continue
            if not path.exists():
                continue
            rel = f"src/{src}"
            if rel in seen:
                continue
            seen.add(rel)
            files.append(rel)
        if not files:
            continue
        if name in names:
            # Same library name used twice (e.g. version-specific splits): merge.
            name = f"{name}_{len(names)}"
        names.append(name)
        lines.append(f"set(LIB_{name}_FILES")
        lines.extend(f"        {f}" for f in files)
        lines.append(")")
    lines.append("")
    lines.append("set(ALL_LIBS")
    lines.extend(f"        {n}" for n in names)
    lines.append(")")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT} ({len(names)} libraries, {len(seen)} files)")


if __name__ == "__main__":
    main()
